#!/usr/bin/env node
// Code provenance for a studio project: reads the `Provenance:` header tag that each source file
// carries, aggregates it into docs/80-provenance.{md,json}, and gates untagged files.
// Zero dependencies. The in-file tag is the source of truth; this script only reports and rolls up.
//
// Usage:
//   node provenance.mjs scan  [projectDir]          Print a summary (no writes). Exit 0.
//   node provenance.mjs write [projectDir]          Scan, then (re)write docs/80-provenance.{md,json}.
//   node provenance.mjs set   <file> <class> [proj] Stamp/replace one file's header, then refresh manifest.
//   node provenance.mjs check [projectDir]          Exit 1 if any source file lacks a valid tag (for gates/CI).
//
// Classes: ai-generated | human-assisted | human-written | legacy
// Taxonomy & header format: skills/code-provenance/SKILL.md

import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { join, resolve, relative, extname, basename } from 'node:path';

export const CLASSES = ['ai-generated', 'human-assisted', 'human-written', 'legacy'];

// Source files we expect a provenance tag on. Swift-first, with the common companions a studio
// project may carry. Everything else (assets, docs, generated manifests) is ignored.
const SOURCE_EXTS = new Set([
  '.swift', '.m', '.mm', '.h', '.c', '.cpp',
  '.js', '.mjs', '.ts', '.tsx', '.kt', '.rb', '.py', '.sh',
]);
// Directories never scanned: VCS, build output, dependencies, and studio bookkeeping.
const SKIP_DIRS = new Set([
  '.git', '.build', 'build', 'DerivedData', 'Pods', 'Carthage', 'node_modules',
  '.swiftpm', 'docs', 'assets', 'design', '.github', 'scripts',
]);
// Individual files that are config/generated, not authored product code.
const SKIP_FILES = new Set(['Package.resolved', 'Package.swift']);

// Comment leader per extension, for `set` to write a header the compiler accepts.
function leaderFor(ext) {
  if (ext === '.rb' || ext === '.py' || ext === '.sh') return '#';
  return '//';
}

const TAG_RE = /Provenance:\s*(ai-generated|human-assisted|human-written|legacy)\b/i;
const HEADER_LINES = 10; // the tag must sit in the first N lines of the file

async function walk(dir, root, out) {
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (e.name.startsWith('.') && e.name !== '.') { if (SKIP_DIRS.has(e.name)) continue; }
    const full = join(dir, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      await walk(full, root, out);
    } else if (e.isFile()) {
      if (SKIP_FILES.has(e.name)) continue;
      if (SOURCE_EXTS.has(extname(e.name))) out.push(full);
    }
  }
  return out;
}

// Classify one file from its header tag. Untagged source files get class `untagged`.
async function classify(full) {
  let text = '';
  try { text = await readFile(full, 'utf8'); } catch { return null; }
  const head = text.split('\n').slice(0, HEADER_LINES).join('\n');
  const m = TAG_RE.exec(head);
  const lines = text.split('\n').filter((l) => l.trim()).length;
  return { cls: m ? m[1].toLowerCase() : 'untagged', lines };
}

async function collect(projectDir) {
  const files = await walk(projectDir, projectDir, []);
  files.sort();
  const rows = [];
  for (const full of files) {
    const c = await classify(full);
    if (c) rows.push({ path: relative(projectDir, full), class: c.cls, lines: c.lines });
  }
  return rows;
}

function totals(rows) {
  const t = Object.fromEntries([...CLASSES, 'untagged'].map((c) => [c, 0]));
  const loc = Object.fromEntries([...CLASSES, 'untagged'].map((c) => [c, 0]));
  for (const r of rows) { t[r.class] = (t[r.class] || 0) + 1; loc[r.class] = (loc[r.class] || 0) + r.lines; }
  return { files: t, loc };
}

function summaryText(rows) {
  const { files, loc } = totals(rows);
  const nFiles = rows.length || 1;
  const nLoc = Object.values(loc).reduce((a, b) => a + b, 0) || 1;
  const pct = (n, d) => `${Math.round((n / d) * 100)}%`;
  const line = (c) => `  ${c.padEnd(15)} ${String(files[c]).padStart(4)} files (${pct(files[c], nFiles).padStart(4)})   ${String(loc[c]).padStart(6)} lines (${pct(loc[c], nLoc).padStart(4)})`;
  let out = 'Provenance\n';
  for (const c of CLASSES) out += line(c) + '\n';
  if (files.untagged) out += line('untagged') + '   ⚠ needs a header tag\n';
  return out;
}

// docs/80-provenance.md — the human-readable manifest, in the docs/ convention.
function manifestMarkdown(rows, projectDir) {
  const { files, loc } = totals(rows);
  const nFiles = rows.length || 1;
  const nLoc = Object.values(loc).reduce((a, b) => a + b, 0) || 1;
  const pct = (n, d) => `${Math.round((n / d) * 100)}%`;
  const now = new Date().toISOString();
  let md = `# Code provenance\n\n`;
  md += `> Generated by \`scripts/provenance.mjs\` on ${now}. Do not edit by hand — it is rebuilt from\n`;
  md += `> each file's \`Provenance:\` header tag. Taxonomy: \`skills/code-provenance/SKILL.md\`.\n\n`;
  md += `## Summary\n\n`;
  md += `| Class | Files | % files | Lines | % lines |\n| --- | ---: | ---: | ---: | ---: |\n`;
  for (const c of CLASSES) md += `| ${c} | ${files[c]} | ${pct(files[c], nFiles)} | ${loc[c]} | ${pct(loc[c], nLoc)} |\n`;
  if (files.untagged) md += `| ⚠ untagged | ${files.untagged} | ${pct(files.untagged, nFiles)} | ${loc.untagged} | ${pct(loc.untagged, nLoc)} |\n`;
  md += `| **total** | **${rows.length}** | | **${nLoc}** | |\n\n`;
  md += `## Files\n\n`;
  md += `| File | Class | Lines |\n| --- | --- | ---: |\n`;
  for (const r of rows) md += `| \`${r.path}\` | ${r.class === 'untagged' ? '⚠ untagged' : r.class} | ${r.lines} |\n`;
  if (!rows.length) md += `| _no source files found_ | | |\n`;
  return md + '\n';
}

async function writeManifest(projectDir, rows) {
  const docsDir = join(projectDir, 'docs');
  const json = { generated: new Date().toISOString(), totals: totals(rows), items: rows };
  await writeFile(join(docsDir, '80-provenance.json'), JSON.stringify(json, null, 2) + '\n');
  await writeFile(join(docsDir, '80-provenance.md'), manifestMarkdown(rows, projectDir));
}

// Insert or replace a file's provenance header. Keeps it on the first non-shebang line.
async function setHeader(file, cls) {
  if (!CLASSES.includes(cls)) throw new Error(`class must be one of: ${CLASSES.join(', ')}`);
  const ext = extname(file);
  const leader = leaderFor(ext);
  const headerLine = `${leader} Provenance: ${cls}`;
  let text = await readFile(file, 'utf8');
  const lines = text.split('\n');
  // Replace an existing tag in the header window, wherever it sits.
  for (let i = 0; i < Math.min(HEADER_LINES, lines.length); i++) {
    if (TAG_RE.test(lines[i])) {
      lines[i] = lines[i].replace(TAG_RE, `Provenance: ${cls}`);
      await writeFile(file, lines.join('\n'));
      return 'updated';
    }
  }
  // No tag yet: insert after a shebang if present, else at the very top.
  const at = lines[0] && lines[0].startsWith('#!') ? 1 : 0;
  lines.splice(at, 0, headerLine);
  await writeFile(file, lines.join('\n'));
  return 'inserted';
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  if (cmd === 'set') {
    const [file, cls, proj] = rest;
    if (!file || !cls) { console.error('usage: provenance.mjs set <file> <class> [projectDir]'); process.exit(2); }
    const action = await setHeader(resolve(file), cls);
    const projectDir = resolve(proj || process.cwd());
    try { await writeManifest(projectDir, await collect(projectDir)); } catch {}
    console.log(`${action} header on ${basename(file)} → ${cls}`);
    return;
  }

  const projectDir = resolve(rest[0] || process.cwd());
  const rows = await collect(projectDir);

  if (cmd === 'check') {
    const untagged = rows.filter((r) => r.class === 'untagged');
    if (untagged.length) {
      console.error(`${untagged.length} source file(s) missing a Provenance header tag:`);
      for (const r of untagged) console.error(`  ${r.path}`);
      console.error(`\nStamp each with: node scripts/provenance.mjs set <file> <class>`);
      process.exit(1);
    }
    console.log(`All ${rows.length} source files carry a provenance tag.`);
    return;
  }

  if (cmd === 'write') {
    await writeManifest(projectDir, rows);
    console.log(summaryText(rows));
    console.log(`Wrote docs/80-provenance.md and docs/80-provenance.json (${rows.length} files).`);
    return;
  }

  if (cmd === 'scan' || !cmd) {
    process.stdout.write(summaryText(rows));
    const untagged = rows.filter((r) => r.class === 'untagged');
    if (untagged.length) console.log(`\n${untagged.length} untagged — run \`provenance.mjs check\` to list them.`);
    return;
  }

  console.error(`unknown command: ${cmd}\nusage: provenance.mjs scan|write|set|check`);
  process.exit(2);
}

main().catch((e) => { console.error(String(e?.stack || e)); process.exit(1); });
